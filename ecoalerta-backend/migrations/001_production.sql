-- EcoAlerta 2.1 - esquema seguro para Supabase/PostgreSQL
-- Ejecute una vez en Supabase > SQL Editor con una cuenta propietaria.

begin;

create table if not exists public.reportesambientales (
  id_reporte bigint generated by default as identity primary key,
  radicado text not null,
  fecha_registro timestamptz not null default now()
);

alter table public.reportesambientales
  add column if not exists id_reporte bigint generated by default as identity,
  add column if not exists radicado_original text default '',
  add column if not exists origen text not null default 'web',
  add column if not exists descripcion_ciudadano text not null default '',
  add column if not exists direccion_declarada text not null default '',
  add column if not exists latitud double precision,
  add column if not exists longitud double precision,
  add column if not exists correo_usuario text default '',
  add column if not exists nombre_usuario text default '',
  add column if not exists direccion_usuario text default '',
  add column if not exists consentimiento_datos boolean not null default false,
  add column if not exists entidad_assigned text default '',
  add column if not exists correo_entidad text default '',
  add column if not exists categoria text default '',
  add column if not exists subcategoria text default '',
  add column if not exists tipo_problema text default '',
  add column if not exists nivel_peligro text default 'medio',
  add column if not exists color text default 'yellow',
  add column if not exists prioridad text default 'yellow',
  add column if not exists entidad_destino text default 'NINGUNA',
  add column if not exists evaluacion_riesgo text default '',
  add column if not exists descripcion_ia text default '',
  add column if not exists ruta_pdf_informe text default '',
  add column if not exists link_google_maps text default '',
  add column if not exists email_enviado boolean not null default false,
  add column if not exists email_intentos integer not null default 0,
  add column if not exists email_error text default '',
  add column if not exists es_valido boolean not null default false,
  add column if not exists justificacion_ia text default '',
  add column if not exists estado text not null default 'RECIBIDO',
  add column if not exists consulta_token_hash text;

create unique index if not exists reportesambientales_radicado_uq
  on public.reportesambientales (radicado);
create index if not exists reportesambientales_fecha_idx
  on public.reportesambientales (fecha_registro desc);
create index if not exists reportesambientales_estado_idx
  on public.reportesambientales (estado);

create table if not exists public.adminusers (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  refresh_token_hash text,
  created_at timestamptz not null default now()
);

alter table public.adminusers
  add column if not exists password_hash text,
  add column if not exists refresh_token_hash text,
  add column if not exists created_at timestamptz not null default now();

create unique index if not exists adminusers_username_uq
  on public.adminusers (username);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  nombre text default '',
  correo text default '',
  mensaje text not null,
  tipo text not null default 'sugerencia',
  fecha_registro timestamptz not null default now()
);

create table if not exists public.entityresponses (
  id bigint generated by default as identity primary key,
  filing_number text not null,
  entity_name text not null,
  response_text text not null default '',
  response_date timestamptz not null default now(),
  attachments jsonb not null default '[]'::jsonb
);

create index if not exists entityresponses_filing_idx
  on public.entityresponses (filing_number, response_date);

alter table public.reportesambientales enable row level security;
alter table public.adminusers enable row level security;
alter table public.feedback enable row level security;
alter table public.entityresponses enable row level security;

-- El navegador y la aplicación móvil nunca acceden directamente a estas tablas.
-- Todas las operaciones pasan por FastAPI usando la service role del servidor.
revoke all on public.reportesambientales from anon, authenticated;
revoke all on public.adminusers from anon, authenticated;
revoke all on public.feedback from anon, authenticated;
revoke all on public.entityresponses from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
grant select, insert, update on public.reportesambientales to service_role;
grant select, insert, update on public.adminusers to service_role;
grant select, insert on public.feedback to service_role;
grant select, insert, update on public.entityresponses to service_role;
grant usage, select on all sequences in schema public to service_role;

do $$
declare policy_record record;
begin
  for policy_record in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('reportesambientales', 'adminusers', 'feedback', 'entityresponses')
  loop
    execute format('drop policy if exists %I on %I.%I',
      policy_record.policyname, policy_record.schemaname, policy_record.tablename);
  end loop;
end $$;

create or replace function public.ecoalerta_metrics()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'total_reportes', count(*),
    'color_green', count(*) filter (where color = 'green'),
    'color_yellow', count(*) filter (where color = 'yellow'),
    'color_red', count(*) filter (where color = 'red'),
    'nivel_alto', count(*) filter (where nivel_peligro = 'alto'),
    'nivel_medio', count(*) filter (where nivel_peligro = 'medio'),
    'nivel_bajo', count(*) filter (where nivel_peligro = 'bajo'),
    'email_enviados', count(*) filter (where email_enviado is true),
    'email_fallidos', count(*) filter (where email_enviado is false and email_intentos > 0),
    'email_sin_envio', count(*) filter (where email_intentos = 0),
    'en_revision', count(*) filter (where estado = 'EN_REVISION')
  )
  from public.reportesambientales;
$$;

revoke all on function public.ecoalerta_metrics() from public, anon, authenticated;
grant execute on function public.ecoalerta_metrics() to service_role;

create or replace view public.powerbi_reportes
with (security_invoker = true)
as
select
  radicado, fecha_registro, origen, categoria, subcategoria, tipo_problema,
  nivel_peligro, color, prioridad, entidad_assigned, entidad_destino,
  estado, es_valido, email_enviado, latitud, longitud
from public.reportesambientales;

revoke all on public.powerbi_reportes from public, anon, authenticated;
grant select on public.powerbi_reportes to service_role;

commit;
